#!/usr/bin/env python3
"""Build the offline Android WebView bundle in app/src/main/assets/www."""
from __future__ import annotations

import json
import os
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MOBILE = ROOT / "mobile"
WWW = MOBILE / "app" / "src" / "main" / "assets" / "www"
ROUTES = {
    "/": "index.html", "/explore": "pages/resources.html", "/find": "pages/recommendations.html",
    "/focus": "pages/focus.html", "/habits": "mobile/dashboard.html", "/guides": "pages/guides.html", "/safety": "pages/digital-safety.html",
    "/about": "pages/about.html", "/feedback": "pages/feedback.html",
}
GUIDES = ("android-wellbeing", "stayfocusd", "focus-mode")


def put_route(route: str, html: str) -> None:
    parts = [p for p in route.strip("/").split("/") if p]
    target = WWW.joinpath(*parts, "index.html") if parts else WWW / "index.html"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(html, encoding="utf-8")


def add_route_meta(html: str, route: str) -> str:
    if '<meta name="mobile-route"' in html:
        return html
    return html.replace("<head>", f'<head>\n  <meta name="mobile-route" content="{route}">', 1)


def add_mobile_css(html: str) -> str:
    return html.replace("</head>", '  <link rel="stylesheet" href="/css/mobile.css">\n</head>', 1)


def add_bottom_nav(html: str) -> str:
    return html.replace("</body>", '  <script src="/js/mobile.js"></script>\n</body>', 1)


def remove_readonly(function, path: str, _error) -> None:
    """Allow replacement of generated assets copied with Windows read-only flags."""
    os.chmod(path, 0o700)
    function(path)


def offline_feedback() -> str:
    return '''<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"><title>Feedback — Good Signal</title><link rel="stylesheet" href="/css/style.css"><link rel="stylesheet" href="/css/mobile.css"></head><body data-page="feedback"><main class="section"><div class="container"><h1>Feedback needs a connection.</h1><p class="lede">This offline app does not send or store feedback. Your answers are not saved. When online, use the Good Signal website to share feedback.</p><a class="btn btn-primary" href="/">Back to Good Signal</a></div></main><script src="/js/theme.js"></script><script src="/js/mobile.js"></script></body></html>'''


def main() -> None:
    resolved_mobile, resolved_www = MOBILE.resolve(), WWW.resolve()
    if resolved_mobile not in resolved_www.parents or resolved_www != MOBILE.resolve() / "app" / "src" / "main" / "assets" / "www":
        raise SystemExit(f"Refusing to write outside the expected mobile bundle path: {resolved_www}")
    if WWW.exists():
        owned = (WWW / ".mobile-bundle-owned").is_file() or (WWW / "mobile-route-manifest.json").is_file()
        if any(path.is_file() for path in WWW.rglob("*")) and not owned:
            raise SystemExit(f"Refusing to replace unmarked output directory: {WWW}")
        if owned:
            shutil.rmtree(WWW, onerror=remove_readonly)
    WWW.mkdir(parents=True, exist_ok=True)
    (WWW / ".mobile-bundle-owned").write_text("Generated by mobile/build_offline.py\n", encoding="utf-8")
    for folder in ("css", "js", "assets"):
        shutil.copytree(ROOT / folder, WWW / folder, dirs_exist_ok=True)
    style = WWW / "css" / "style.css"
    css = style.read_text(encoding="utf-8")
    css = css.replace("@import url('https://fonts.googleapis.com/css2?family=Bricolage+Grotesque:opsz,wdth,wght@12..96,75..100,500..800&family=IBM+Plex+Mono:wght@400;500&family=Public+Sans:wght@400;500;600;700&display=swap');", "")
    style.write_text(css, encoding="utf-8")
    shutil.copy2(MOBILE / "mobile.js", WWW / "js/mobile.js")
    shutil.copy2(MOBILE / "mobile.css", WWW / "css/mobile.css")
    shutil.copy2(MOBILE / "dashboard.js", WWW / "js/dashboard.js")
    shutil.copy2(MOBILE / "dashboard.css", WWW / "css/dashboard.css")
    for route, source_path in ROUTES.items():
        if route == "/feedback":
            html = offline_feedback()
        elif route in ("/", "/habits"):
            html = add_route_meta((MOBILE / "dashboard.html").read_text(encoding="utf-8"), route)
            html = add_mobile_css(html)
            html = add_bottom_nav(html)
        else:
            html = add_route_meta((ROOT / source_path).read_text(encoding="utf-8"), route)
            html = add_mobile_css(html)
            html = add_bottom_nav(html)
        put_route(route, html)

    # Import the app's existing escaped server renderer only at build time; runtime is static.
    sys.path.insert(0, str(ROOT))
    from server import load_resources, resource_detail_html

    for guide in GUIDES:
        route = f"/guide/{guide}"
        html = add_route_meta((ROOT / "guides" / f"{guide}.html").read_text(encoding="utf-8"), route)
        put_route(route, add_bottom_nav(add_mobile_css(html)))
    for item in load_resources():
        html = resource_detail_html(item)
        route = f"/resource/{item['id']}"
        html = add_route_meta(html, route)
        put_route(route, add_bottom_nav(add_mobile_css(html)))

    (WWW / "data").mkdir(exist_ok=True)
    shutil.copy2(ROOT / "data/resources.json", WWW / "data/resources.json")
    shutil.copy2(MOBILE / "mobile.js", WWW / "js/mobile.js")
    shutil.copy2(MOBILE / "mobile.css", WWW / "css/mobile.css")
    shutil.copy2(MOBILE / "dashboard.js", WWW / "js/dashboard.js")
    shutil.copy2(MOBILE / "dashboard.css", WWW / "css/dashboard.css")
    app_js = WWW / "js/app.js"
    js = app_js.read_text(encoding="utf-8")
    # Replace server-only feedback handling and API hydration.
    start = js.find("  function setupFeedbackForm() {")
    end = js.find("\n  function showToast(", start)
    if start < 0 or end < 0:
        raise SystemExit("Could not locate bounded feedback-handler markers in js/app.js")
    js = js[:start] + "  function setupFeedbackForm() {}\n" + js[end:]
    fetch_start = js.find("    const controller = new AbortController();")
    render_start = js.find("    renderFeatured();", fetch_start)
    if fetch_start < 0 or render_start < 0:
        raise SystemExit("Could not locate API hydration block in js/app.js")
    js = js[:fetch_start] + js[render_start:]
    js = js.replace("    setupFeedbackForm();\n", "")
    app_js.write_text(js, encoding="utf-8")
    if "fetch(" in js or "/api/" in js:
        raise SystemExit("Generated app.js still contains a runtime API request")

    safety = WWW / "safety" / "index.html"
    text = safety.read_text(encoding="utf-8")
    text = text.replace("<main id=\"main-content\">", '<main id="main-content"><div class="container"><a class="settings-shortcut" href="/android-settings" data-android-settings>Open Android Digital Wellbeing settings</a></div>', 1)
    safety.write_text(text, encoding="utf-8")

    resources = load_resources()
    manifest = {
        "origin": "https://appassets.androidplatform.net", "entry": "/",
        "routeFiles": {route: ("index.html" if route == "/" else route.lstrip("/") + "/index.html") for route in ROUTES},
        "guides": {f"/guide/{g}": f"guide/{g}/index.html" for g in GUIDES},
        "resources": {f"/resource/{r['id']}": f"resource/{r['id']}/index.html" for r in resources},
        "nativeActions": {"/android-settings": "Intercept route and open Android Digital Wellbeing settings. Fallback is /guide/android-wellbeing/."},
        "staticAssets": "Resolve exact /<path> assets to www/<path>; keep root-absolute URLs unchanged.",
    }
    (WWW / "mobile-route-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Built {sum(1 for p in WWW.rglob('*') if p.is_file())} files into {WWW}")


if __name__ == "__main__":
    main()
